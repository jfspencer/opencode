// How the shell tool's command scanner reads many command shapes. Each scenario sends one family of commands as
// parallel shell calls in a single step. The session denies every shell command, so nothing the scanner
// understands runs: each call ends as denied (a permission resource was found), as refused (the scanner cannot
// analyze it, with the reason), or runs because it holds no command at all (assignments, declarations, cd within
// the project). The exact resources each command asks for are recorded by shell-classify.test.ts.
//
// The calls run concurrently, so the event stream (whose interleaving is not defined) is not recorded; the
// provider request after the step and the session's messages list every outcome in call order.
import { HIDDEN_TOOLS } from "../lib/model"
import { say } from "../lib/openrouter"
import { scenario } from "../lib/scenario"
import { mkdirSync, writeFileSync } from "node:fs"
import path from "node:path"

type Effect = "allow" | "deny" | "ask"
const rule = (action: string, resource: string, effect: Effect) => ({ action, resource, effect })
const only = [...HIDDEN_TOOLS.map((action) => rule(action, "*", "deny")), rule("*", "*", "deny")]
const agents = { build: { system: "Conformance agent." } }

const files = {
  "README.md": "# Demo\n",
  "a.txt": "alpha\n",
  "b.txt": "beta\n",
  "src/main.ts": "export {}\n",
}

/** Scan a family of commands under the given shell (default: bash, from $SHELL). */
function family(name: string, commands: readonly string[], shell?: string) {
  scenario(
    name,
    {
      files,
      events: false,
      // The session denies every command. Its rule is `?*` (any non-empty resource) rather than `*`, which would
      // remove the shell tool from the model's tool list altogether.
      config: { agents, ...(shell ? { shell } : {}), permissions: [...only, rule("shell", "*", "ask")] },
      turns: [{ events: commands.map((command, index) => ({ tool: "shell", input: { command }, id: `call_${index}` })) }, say("Done.")],
    },
    async (ctx) => {
      const id = await ctx.session({ title: name, permissions: [rule("shell", "?*", "deny")] })
      await ctx.http("POST", `/api/session/${id}/prompt`, { text: `Run the ${name} commands.` })
      await ctx.wait(id)
    },
  )
}

