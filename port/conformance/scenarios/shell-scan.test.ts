// Zsh and PowerShell are not installed where the reference runs, but the scanner picks its dialect from the
// configured shell's name. A stand-in executable named after each shell makes the configuration valid. It accepts
// any command and does nothing, so commands that hold no permission resource "run" with no output; everything
// else is refused or denied before anything runs.
const fakeShells = path.join(process.env.CONFORMANCE_ROOT!, "fake-shells")
mkdirSync(fakeShells, { recursive: true })
for (const name of ["zsh", "pwsh"])
  writeFileSync(path.join(fakeShells, name), "#!/bin/sh\n# Stand-in for a shell that is not installed.\nexit 0\n", { mode: 0o755 })

