// Emits Rust source from the model. Output is a pure function of the model, which follows declaration order, so
// regenerating is byte-identical and an upstream change shows up as a local diff.
//
// Decoders report Effect's messages (see lower.ts): where a Rust type's own `Wire::decode` reports exactly the
// node's messages (the defaults below, which mirror crate::wire), it is used as is; otherwise the decoder is spelled
// out with the messages passed in.
import type { Check, Def, Field, Lit, MemberMap, Site, Ty } from "./lower.ts"
import type { Model, RootTy } from "./model.ts"
import { jsRegexToRust } from "./regex.ts"

// The messages of crate::wire's own `Wire` impls.
const DEFAULT = {
  string: "Expected string",
  number: "Expected number",
  int: "Expected an integer",
  boolean: "Expected boolean",
  null: "Expected null",
  notNull: "Expected object | array",
  array: "Expected array",
  object: "Expected object",
  finite: "Expected a finite number",
  base64: "Expected a valid Base64 string",
  duration: "Expected a valid Duration string",
  jsnumber: {
    te: 'Expected number | "Infinity" | "-Infinity" | "NaN"',
    nonFinite: "Expected a finite number",
    str: 'Expected "Infinity" | "-Infinity" | "NaN"',
  },
}

/** `Literal.getExpected`. */
const literalText = (v: Lit) => (typeof v === "string" ? JSON.stringify(v) : String(v))

const HEADER = (what: string) =>
  `// @generated by port/rust/gen (port/scripts/gen-types.sh) from the TS reference's Effect schemas: ${what}.\n` +
  `// Do not edit: regenerate instead. See port/README.md.\n`

const KEYWORDS = new Set(
  "as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv typeof unsized virtual yield try gen".split(
    " ",
  ),
)

export const pascal = (s: string) => {
  const name = s
    .split(/[^A-Za-z0-9]+/)
    .filter((p) => p.length > 0)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("")
  return /^[0-9]/.test(name) ? `N${name}` : name
}

export const snake = (key: string) => {
  let s = key
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .toLowerCase()
    .replace(/^_+|_+$/g, "")
  if (!s) s = "field"
  if (/^[0-9]/.test(s)) s = `n${s}`
  if (s === "self" || s === "super" || s === "crate") return `${s}_`
  return KEYWORDS.has(s) ? `r#${s}` : s
}

const rustString = (s: string) => JSON.stringify(s).replace(/\\u([0-9a-fA-F]{4})/g, "\\u{$1}")
const rawString = (s: string) => {
  let hashes = "#"
  while (s.includes(`"${hashes}`)) hashes += "#"
  return `r${hashes}"${s}"${hashes}`
}

const isInt = (checks: Check[]) => checks.some((c) => c.k === "int")

export function emit(model: Model) {
  const defs = new Map(model.defs.map((d) => [d.name, d]))
  const literals = new Literals()
  const patterns = new Patterns()
  const sites = new Sites()
  const boxed = recursion(model.defs)
  // Union definitions a nullable decodes member by member (`X | Y | null`).
  const memberwise = new Set<string>()

  // ---- type expressions ---------------------------------------------------------------------------------
  const rty = (ty: Ty, box: ReadonlySet<string> = new Set()): string => {
    switch (ty.t) {
      case "ref":
        return box.has(ty.name) ? `Box<${ty.name}>` : ty.name
      case "string":
      case "trim":
        return "String"
      case "number":
        return isInt(ty.checks) ? "i64" : "f64"
      case "jsnumber":
        return "rt::JsNumber"
      case "boolean":
        return "bool"
      case "null":
        return "rt::Null"
      case "literal":
        return `lit::${literals.name(ty.value)}`
      case "json":
        return ty.nonNull ? "rt::NotNull" : "Json"
      case "array":
        return `Vec<${rty(ty.item)}>`
      case "arrayFromSingle":
      case "union1":
      case "pre":
        return rty(ty.inner, box)
      case "arrayEnsure":
        return `rt::ArrayEnsure<${rty(ty.item)}>`
      case "tuple":
        return `Vec<${rty(homogeneous(ty))}>`
      case "record":
        return `rt::Record<${rty(ty.key)}, ${rty(ty.value)}>`
      case "nullable":
        return `Option<${rty(ty.inner, box)}>`
      case "numberString":
        return isInt(ty.num) ? "rt::IntString" : "rt::NumberString"
      case "millis":
        return "rt::EpochMillis"
      case "jsonString":
        return `rt::JsonString<${rty(ty.inner, box)}>`
      case "base64":
        return "rt::Base64"
      case "duration":
        return "rt::Duration"
      case "custom":
        return rty(ty.target ?? ty.wire, box)
      default:
        throw new Error(`no Rust type for ${ty.t}`)
    }
  }

  // Whether decoding needs more than the Rust type's own `Wire::decode`: inline checks, codecs, or messages other
  // than the defaults of crate::wire.
  const custom = (ty: Ty): boolean => {
    switch (ty.t) {
      case "string":
        return ty.checks.length > 0 || ty.te !== DEFAULT.string
      case "number":
        return isInt(ty.checks)
          ? !(ty.te === DEFAULT.number && ty.checks.length === 1 && ty.checks[0].msg === DEFAULT.int)
          : ty.checks.length > 0 || ty.te !== DEFAULT.number
      case "jsnumber":
        return (
          ty.checks.length > 0 ||
          ty.te !== DEFAULT.jsnumber.te ||
          ty.nonFinite !== DEFAULT.jsnumber.nonFinite ||
          ty.str !== DEFAULT.jsnumber.str
        )
      case "boolean":
        return ty.te !== DEFAULT.boolean
      case "null":
        return ty.te !== DEFAULT.null
      case "literal":
        return ty.te !== `Expected ${literalText(ty.value)}`
      case "json":
        return ty.nonNull && ty.te !== DEFAULT.notNull
      case "array":
        return ty.te !== DEFAULT.array || ty.checks.length > 0 || custom(ty.item)
      case "never":
      case "tuple":
      case "trim":
      case "arrayEnsure":
      case "arrayFromSingle":
      case "nullable":
      case "union1":
      case "pre":
        return true
      case "record":
        return ty.te !== DEFAULT.object || custom(ty.value)
      case "numberString":
        return isInt(ty.num)
          ? !(ty.te === DEFAULT.string && ty.wire.length === 0 && ty.num.length === 1 && ty.num[0].msg === DEFAULT.int)
          : ty.te !== DEFAULT.string || ty.wire.length > 0 || ty.num.length > 0
      case "millis":
        return !(ty.te === DEFAULT.number && ty.checks.length === 1 && ty.checks[0].k === "finite" && ty.checks[0].msg === DEFAULT.finite)
      case "base64":
        return ty.te !== DEFAULT.string || ty.invalid !== DEFAULT.base64
      case "duration":
        return ty.te !== DEFAULT.string || ty.invalid !== DEFAULT.duration
      case "custom":
        return ty.hook !== undefined || custom(ty.wire)
      case "jsonString":
        if (custom(ty.inner)) throw new Error("JSON string of an inline checked type")
        return ty.te !== DEFAULT.string
      default:
        return false
    }
  }

  /** Checks in declaration order, each reporting its message. `kind` is how `x` holds the value. */
  const checkStmts = (checks: Check[], x: string, kind: "str" | "num" | "f64" | "items"): string =>
    checks
      .map((c) => {
        const n = kind === "num" ? `*${x}` : x
        const m = rustString(c.msg)
        switch (c.k) {
          case "minLength":
            return kind === "items" ? `rt::check::min_items(${x}, ${c.n}, ${m})?;` : `rt::check::min_length(${x}, ${c.n}, ${m})?;`
          case "maxLength":
            return kind === "items" ? `rt::check::max_items(${x}, ${c.n}, ${m})?;` : `rt::check::max_length(${x}, ${c.n}, ${m})?;`
          case "pattern":
            return `rt::check::pattern(${x}, &patterns::${patterns.name(c.source, c.flags)}, ${m})?;`
          case "startsWith":
            return `rt::check::starts_with(${x}, ${rustString(c.s)}, ${m})?;`
          case "endsWith":
            return `rt::check::ends_with(${x}, ${rustString(c.s)}, ${m})?;`
          case "includes":
            return `rt::check::includes(${x}, ${rustString(c.s)}, ${m})?;`
          case "trimmed":
            return `rt::check::trimmed(${x}, ${m})?;`
          case "unique":
            return `rt::check::unique(${x}, ${m})?;`
          case "int":
            return `rt::check::int(${n}, ${m})?;`
          case "finite":
            return `rt::check::finite(${n}, ${m})?;`
          case "gt":
          case "gte":
          case "lt":
          case "lte":
            return `rt::check::${c.k}(${n}, ${f64(c.n)}, ${m})?;`
        }
      })
      .join(" ")

  const checked = (base: string, stmts: string) => (stmts ? `rt::checked(${base}, |x| { ${stmts} Ok(()) })` : base)
  const checkFn = (stmts: string) => (stmts ? `|x| { ${stmts} Ok(()) }` : "|_| Ok(())")
  const quote = rustString

  /** Decoding through a TS union's site: `arms` maps candidate (TS member) indices to member decoders. */
  const anyOf = (site: Site, v: string, arms: Array<readonly [number, string]>, oneOf?: string) => {
    const match = `|i| match i { ${arms.map(([i, e]) => `${i} => ${e},`).join(" ")} _ => unreachable!("not a candidate") }`
    const s = `&sites::${sites.name(site)}`
    return oneOf === undefined ? `rt::any_of(${v}, ${s}, ${match})` : `rt::one_of(${v}, ${s}, ${quote(oneOf)}, ${match})`
  }
  const arms = (map: MemberMap, arm: (k: number | "null") => string) =>
    map.flatMap((k, i) => (k === "none" ? [] : [[i, arm(k)] as const]))

  /** A Rust expression of type `Result<rty(ty), Issue>` decoding `v: &Json`. */
  const decode = (ty: Ty, v: string, box: ReadonlySet<string> = new Set()): string => {
    if (!custom(ty)) return `<${rty(ty, box)} as Wire>::decode(${v})`
    switch (ty.t) {
      case "string":
        return checked(`rt::string(${v}, ${quote(ty.te)})`, checkStmts(ty.checks, "x", "str"))
      case "number":
        return isInt(ty.checks)
          ? `rt::int(${v}, ${quote(ty.te)}, ${checkFn(checkStmts(ty.checks, "x", "f64"))})`
          : checked(`rt::number(${v}, ${quote(ty.te)})`, checkStmts(ty.checks, "x", "num"))
      case "jsnumber":
        return checked(
          `rt::JsNumber::decode_with(${v}, &rt::JsNumberMessages { te: ${quote(ty.te)}, non_finite: ${quote(ty.nonFinite)}, string: ${quote(ty.str)} })`,
          checkStmts(ty.checks, "(&x.0)", "num"),
        )
      case "boolean":
        return `rt::boolean(${v}, ${quote(ty.te)})`
      case "null":
        return `rt::null(${v}, ${quote(ty.te)})`
      case "literal":
        return `rt::literal(${v}, ${litJson(ty.value)}, ${quote(ty.te)}).map(|_| lit::${literals.name(ty.value)})`
      case "never":
        return `rt::never(${v}, ${quote(ty.te)})`
      case "json":
        return `rt::NotNull::decode_with(${v}, ${quote(ty.te!)})`
      case "array":
        return checked(`rt::array(${v}, ${quote(ty.te)}, |v| ${decode(ty.item, "v")})`, checkStmts(ty.checks, "x", "items"))
      case "tuple": {
        const item = homogeneous(ty)
        const missing = [...new Set(ty.elements.map((e) => e.missing))]
        if (missing.length !== 1) throw new Error("tuple elements with different missing-key messages")
        return checked(
          `rt::tuple(${v}, ${quote(ty.te)}, ${ty.elements.length}, ${quote(missing[0])}, |v| ${decode(item, "v")})`,
          checkStmts(ty.checks, "x", "items"),
        )
      }
      case "record":
        return `rt::record::<${rty(ty.key)}, ${rty(ty.value)}>(${v}, ${quote(ty.te)}, |v| ${decode(ty.value, "v")})`
      case "nullable": {
        // One non-null member: decode it; several: the inner union (or enum) member by member, so the candidates
        // are those of the whole `X | Y | null`.
        const several = new Set(ty.map.filter((k) => typeof k === "number")).size > 1
        const member = (k: number) => {
          if (!several) return decode(ty.inner, v, box)
          if (ty.inner.t !== "ref") throw new Error(`nullable of several members over ${ty.inner.t}`)
          const def = defs.get(ty.inner.name)!
          const wrap = box.has(ty.inner.name) ? ".map(Box::new)" : ""
          if (def.kind === "enum")
            return `rt::literal(${v}, ${litJson(def.values[k])}, ${quote(ty.site.te)}).map(|_| ${def.name}::${enumNames(def.values)[k]})${wrap}`
          if (def.kind !== "union") throw new Error(`nullable of several members over ${def.kind}`)
          memberwise.add(def.name)
          return `${def.name}::member(${v}, ${k})${wrap}`
        }
        return anyOf(
          ty.site,
          v,
          arms(ty.map, (k) => (k === "null" ? "Ok(None)" : `${member(k)}.map(Some)`)),
        )
      }
      case "numberString": {
        const int = isInt(ty.num)
        const parsed = `rt::number_string(${v}, ${quote(ty.te)}, ${checkFn(checkStmts(ty.wire, "x", "str"))}, ${checkFn(checkStmts(ty.num, "x", "num"))})`
        return int ? `${parsed}.map(|n| rt::IntString(n as i64))` : `${parsed}.map(rt::NumberString)`
      }
      case "trim":
        return `rt::trim(${v}, ${quote(ty.te)}, ${checkFn(checkStmts(ty.wire, "x", "str"))}, ${checkFn(checkStmts(ty.checks, "x", "str"))})`
      case "millis":
        return `rt::EpochMillis::decode_with(${v}, ${quote(ty.te)}, ${checkFn(checkStmts(ty.checks, "x", "f64"))})`
      case "arrayEnsure":
        return anyOf(
          ty.site,
          v,
          arms(ty.map, (k) =>
            k === 0 ? `${decode(ty.item, v)}.map(|x| rt::ArrayEnsure(vec![x]))` : `${decode(ty.many, v)}.map(rt::ArrayEnsure)`,
          ),
        )
      case "arrayFromSingle":
        return `rt::array_from_single(${v}, ${quote(ty.te)}, |v| ${decode(ty.inner, "v", box)})`
      case "union1":
        return anyOf(
          ty.site,
          v,
          arms(ty.map, () => decode(ty.inner, v, box)),
        )
      case "pre":
        return `rt::pre(${v}, |v| ${decode(ty.wire, "v")}, |v| ${decode(ty.inner, "v", box)})`
      case "jsonString":
        return `rt::JsonString::decode_with(${v}, ${quote(ty.te)}, |v| ${decode(ty.inner, "v", box)})`
      case "base64":
        return `rt::Base64::decode_with(${v}, ${quote(ty.te)}, ${quote(ty.invalid)})`
      case "duration":
        return `rt::Duration::decode_with(${v}, ${quote(ty.te)}, ${quote(ty.invalid)})`
      case "custom":
        return ty.hook
          ? `rt::hooked(${v}, |v| ${decode(ty.wire, "v")}, rt::hook::${ty.hook}, |v| ${decode(ty.target!, "v", box)})`
          : decode(ty.wire, v, box)
      default:
        throw new Error(`no custom decoder for ${ty.t}`)
    }
  }

  // ---- definitions --------------------------------------------------------------------------------------
  const docLines = (doc: string | undefined, indent = "") =>
    doc
      ? doc
          .split("\n")
          .map((l) => `${indent}///${l ? ` ${l}` : ""}\n`)
          .join("")
      : ""

  const out: string[] = []
  const unenforced: string[] = []

  const emitStruct = (def: Extract<Def, { kind: "struct" }>) => {
    const box = boxed.get(def.name) ?? new Set<string>()
    if (def.checks.length) unenforced.push(`${def.name}: struct-level checks ${JSON.stringify(def.checks)}`)
    if (def.rest.length > 1) throw new Error(`${def.name}: several index signatures`)
    const idents = new Set<string>()
    const ident = (key: string) => {
      let name = snake(key)
      for (let i = 2; idents.has(name); i++) name = `${snake(key)}_${i}`
      idents.add(name)
      return name
    }
    // `key?: never`: the key must be absent; nothing is stored.
    const absent = def.fields.filter((f) => f.ty.t === "never")
    if (absent.some((f) => !f.optional)) throw new Error(`${def.name}: a required key of type never`)
    const fields = def.fields.filter((f) => f.ty.t !== "never").map((f) => ({ f, id: ident(f.key) }))
    const restId = def.rest.length ? ident("rest") : undefined
    const fieldType = (f: Field) => {
      const t = rty(f.ty, box)
      return f.optional && f.default === undefined ? `Option<${t}>` : t
    }
    let s = docLines(def.doc)
    s += `#[derive(Debug, Clone, PartialEq)]\npub struct ${def.name} {\n`
    for (const { f, id } of fields) {
      s += docLines(f.doc, "    ")
      if (snake(f.key) !== f.key || id !== f.key) s += `    /// Wire key: \`${f.key.replace(/`/g, "")}\`${f.default !== undefined ? ` (default ${JSON.stringify(f.default)})` : ""}${f.catchNone ? " (invalid values are dropped)" : ""}\n`
      else if (f.default !== undefined || f.catchNone) s += `    /// ${f.default !== undefined ? `Default ${JSON.stringify(f.default)}` : "Invalid values are dropped"}\n`
      s += `    pub ${id}: ${fieldType(f)},\n`
    }
    if (restId) {
      const r = def.rest[0]
      s += `    /// Keys beyond the declared ones (index signature).\n    pub ${restId}: rt::Record<${rty(r.key)}, ${rty(r.value)}>,\n`
    }
    // Keys in declaration order, as Effect checks them (absent keys included), then the index signature.
    s += `}\n\nimpl Wire for ${def.name} {\n    fn decode(v: &Json) -> Result<Self, Issue> {\n        let o = rt::object(v, ${rustString(def.te)})?;\n`
    // Locals are `f0`, `f1`, ... so no field name shadows `o` or `v`.
    const local = new Map(fields.map(({ f }, i) => [f, `f${i}`]))
    for (const f of def.fields) {
      const key = rustString(f.key)
      const id = local.get(f)
      if (id === undefined) {
        s += `        rt::absent(o, ${key}, ${rustString((f.ty as { te: string }).te)})?;\n`
        continue
      }
      const d = decode(f.ty, "v", box)
      if (f.default !== undefined) s += `        let ${id} = rt::defaulted(o, ${key}, ${rawString(JSON.stringify(f.default))}, |v| ${d})?;\n`
      else if (f.catchNone) s += `        let ${id} = rt::optional_lenient(o, ${key}, |v| ${d});\n`
      else if (f.optional) s += `        let ${id} = rt::optional(o, ${key}, |v| ${d})?;\n`
      else s += `        let ${id} = rt::required(o, ${key}, ${rustString(f.missing)}, |v| ${d})?;\n`
    }
    if (restId) {
      const r = def.rest[0]
      const declared = def.fields.map((f) => rustString(f.key)).join(", ")
      s += `        let rest = rt::rest::<${rty(r.key)}, ${rty(r.value)}>(o, &[${declared}], |v| ${decode(r.value, "v")})?;\n`
    }
    const inits = [...fields.map(({ f, id }) => `${id}: ${local.get(f)}`), ...(restId ? [`${restId}: rest`] : [])]
    s += `        Ok(Self { ${inits.join(", ")} })\n    }\n\n    fn encode(&self, out: &mut Out) {\n`
    const indexKeys = def.fields.some((f) => /^(0|[1-9][0-9]{0,9})$/.test(f.key))
    if (restId || indexKeys) {
      // JS property order over declared and extra keys: build the entries, then write them in that order.
      s += `        let mut entries: Vec<(&str, String)> = Vec::new();\n`
      for (const { f, id } of fields) {
        const key = rustString(f.key)
        if (f.optional && f.default === undefined)
          s += `        if let Some(x) = &self.${id} { entries.push((${key}, rt::to_string(x))); }\n`
        else s += `        entries.push((${key}, rt::to_string(&self.${id})));\n`
      }
      if (restId) s += `        for (k, x) in &self.${restId}.0 { entries.push((rt::Key::as_key(k), rt::to_string(x))); }\n`
      s += `        rt::write_entries(out, entries);\n`
    } else {
      s += fields.length ? `        let mut o = out.object();\n` : `        let _o = out.object();\n`
      for (const { f, id } of fields) {
        const key = rustString(f.key)
        if (f.optional && f.default === undefined) s += `        if let Some(x) = &self.${id} { x.encode(o.key(${key})); }\n`
        else s += `        self.${id}.encode(o.key(${key}));\n`
      }
    }
    s += `    }\n}\n`
    out.push(s)
  }

  const variantNames = (union: string, members: Ty[]) => {
    const used = new Set<string>()
    return members.map((m, i) => {
      let base = variantBase(union, m)
      if (used.has(base)) base = `${base}${i}`
      used.add(base)
      return base
    })
  }
  const variantBase = (union: string, m: Ty): string => {
    switch (m.t) {
      case "ref":
        return m.name.startsWith(union) && /^[A-Z]/.test(m.name.slice(union.length)) ? m.name.slice(union.length) : m.name
      case "literal":
        return literals.name(m.value)
      case "string":
      case "trim":
        return "String"
      case "number":
        return isInt(m.checks) ? "Int" : "Number"
      case "jsnumber":
        return "Number"
      case "boolean":
        return "Bool"
      case "null":
        return "Null"
      case "json":
        return "Json"
      case "array":
      case "tuple":
      case "arrayEnsure":
      case "arrayFromSingle":
        return "Array"
      case "record":
        return "Record"
      case "nullable":
        return `${variantBase(union, m.inner)}OrNull`
      case "union1":
      case "pre":
        return variantBase(union, m.inner)
      case "custom":
        return variantBase(union, m.target ?? m.wire)
      default:
        return pascal(m.t)
    }
  }

  // Effect tries only the candidates its index selects for the input (wire/union.rs), in member order.
  const emitUnion = (def: Extract<Def, { kind: "union" }>) => {
    const box = boxed.get(def.name) ?? new Set<string>()
    const names = variantNames(def.name, def.members)
    const member = (k: number) => `${decode(def.members[k], "v", box)}.map(Self::${names[k]})`
    let s = docLines(def.doc)
    s += `#[derive(Debug, Clone, PartialEq)]\npub enum ${def.name} {\n`
    def.members.forEach((m, i) => (s += `    ${names[i]}(${rty(m, box)}),\n`))
    s += `}\n\nimpl Wire for ${def.name} {\n    fn decode(v: &Json) -> Result<Self, Issue> {\n`
    s += `        ${anyOf(
      def.site,
      "v",
      arms(def.map, (k) => member(k as number)),
      def.oneOf,
    )}\n`
    s += `    }\n\n    fn encode(&self, out: &mut Out) {\n        match self {\n`
    names.forEach((n) => (s += `            Self::${n}(x) => x.encode(out),\n`))
    s += `        }\n    }\n}\n`
    out.push(s)
    memberDecoders.set(def.name, def.members.map((_, k) => member(k)))
  }
  const memberDecoders = new Map<string, string[]>()

  const enumNames = (values: Lit[]) => {
    const used = new Set<string>()
    return values.map((v, i) => {
      let n = literals.name(v)
      if (used.has(n)) n = `${n}${i}`
      used.add(n)
      return n
    })
  }

  const emitEnum = (def: Extract<Def, { kind: "enum" }>) => {
    const names = enumNames(def.values)
    let s = docLines(def.doc)
    s += `#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub enum ${def.name} {\n`
    def.values.forEach((v, i) => (s += `    /// ${JSON.stringify(v)}\n    ${names[i]},\n`))
    s += `}\n\n`
    if (def.values.every((v) => typeof v === "string")) {
      s += `impl ${def.name} {\n    pub const fn as_str(&self) -> &'static str {\n        match self {\n`
      def.values.forEach((v, i) => (s += `            Self::${names[i]} => ${rustString(v as string)},\n`))
      s += `        }\n    }\n}\n\n`
    }
    s += `impl Wire for ${def.name} {\n    fn decode(v: &Json) -> Result<Self, Issue> {\n        match v {\n`
    const strings = def.values.map((v, i) => [v, i] as const).filter(([v]) => typeof v === "string")
    if (strings.length) {
      s += `            Json::String(s) => match s.as_str() {\n`
      for (const [v, i] of strings) s += `                ${rustString(v as string)} => Ok(Self::${names[i]}),\n`
      s += `                _ => Err(rt::Issue::new(${rustString(def.te)})),\n            },\n`
    }
    def.values.forEach((v, i) => {
      if (typeof v === "number") s += `            Json::Number(n) if *n == ${f64(v)} => Ok(Self::${names[i]}),\n`
      if (typeof v === "boolean") s += `            Json::Bool(${v}) => Ok(Self::${names[i]}),\n`
    })
    s += `            _ => Err(rt::Issue::new(${rustString(def.te)})),\n        }\n    }\n\n    fn encode(&self, out: &mut Out) {\n        match self {\n`
    def.values.forEach((v, i) => {
      const w = typeof v === "string" ? `out.string(${rustString(v)})` : typeof v === "number" ? `out.number(${f64(v)})` : `out.bool(${v})`
      s += `            Self::${names[i]} => ${w},\n`
    })
    s += `        }\n    }\n}\n`
    out.push(s)
  }

  const emitNewtype = (def: Extract<Def, { kind: "newtype" }>) => {
    const box = boxed.get(def.name) ?? new Set<string>()
    const inner = rty(def.ty, box)
    const stringy = inner === "String"
    let s = docLines(def.doc)
    s += `#[derive(Debug, Clone, PartialEq${stringy ? ", Eq, Hash, PartialOrd, Ord" : ""})]\npub struct ${def.name}(pub ${inner});\n\n`
    s += `impl Wire for ${def.name} {\n    fn decode(v: &Json) -> Result<Self, Issue> {\n        ${decode(def.ty, "v", box)}.map(Self)\n    }\n\n    fn encode(&self, out: &mut Out) {\n        self.0.encode(out)\n    }\n}\n`
    if (stringy) {
      s += `\nimpl rt::Key for ${def.name} {\n    fn from_key(key: &str) -> Option<Self> {\n        Self::decode(&Json::String(key.to_owned())).ok()\n    }\n\n    fn as_key(&self) -> &str {\n        &self.0\n    }\n}\n`
      s += `\nimpl std::ops::Deref for ${def.name} {\n    type Target = str;\n\n    fn deref(&self) -> &str {\n        &self.0\n    }\n}\n`
    }
    out.push(s)
  }

  for (const def of model.defs) {
    if (def.kind === "struct") emitStruct(def)
    else if (def.kind === "union") emitUnion(def)
    else if (def.kind === "enum") emitEnum(def)
    else emitNewtype(def)
  }

  // Roots without a definition of their own: an alias, or a newtype when decoding needs inline checks.
  const rootDefs: string[] = []
  const emittedRoots = new Set<string>()
  for (const root of model.roots) {
    if (root.ty.t === "ref" || emittedRoots.has(root.name)) continue
    emittedRoots.add(root.name)
    const doc = `/// ${root.root.origin}\n`
    if (custom(root.ty))
      rootDefs.push(
        `${doc}#[derive(Debug, Clone, PartialEq)]\npub struct ${root.name}(pub ${rty(root.ty)});\n\nimpl Wire for ${root.name} {\n    fn decode(v: &Json) -> Result<Self, Issue> {\n        ${decode(root.ty, "v")}.map(Self)\n    }\n\n    fn encode(&self, out: &mut Out) {\n        self.0.encode(out)\n    }\n}\n`,
      )
    else rootDefs.push(`${doc}pub type ${root.name} = ${rty(root.ty)};\n`)
  }

  // Member-by-member decoders of the unions a nullable decodes through its own site.
  const members = [...memberwise].sort().map((name) => {
    const arms = memberDecoders.get(name)!.map((d, k) => `            ${k} => ${d},\n`)
    return `impl ${name} {\n    /// Decodes \`v\` as member \`k\` alone (for the \`X | Y | null\` it belongs to).\n    pub(crate) fn member(v: &Json, k: usize) -> Result<Self, Issue> {\n        match k {\n${arms.join("")}            _ => unreachable!("no such member"),\n        }\n    }\n}\n`
  })

  const types =
    HEADER("types") +
    `#![allow(clippy::all, non_camel_case_types, unused_imports)]\n\n` +
    `use crate::wire::{self as rt, Issue, Json, Out, Wire};\n\n` +
    literals.emit() +
    "\n" +
    patterns.emit() +
    "\n" +
    sites.emit() +
    "\n" +
    out.join("\n") +
    (members.length ? `\n// ---- union members decoded one by one ----\n\n${members.join("\n")}` : "") +
    "\n// ---- roots without a definition of their own ----\n\n" +
    rootDefs.join("\n")

  return { types, routes: emitRoutes(model), events: emitEvents(model), roots: emitRoots(model), unenforced }
}

function homogeneous(ty: Extract<Ty, { t: "tuple" }>): Ty {
  const all = [...ty.elements.map((e) => e.ty), ...ty.rest]
  const first = JSON.stringify(all[0])
  if (ty.rest.length !== 1 || ty.elements.some((e) => e.optional) || all.some((t) => JSON.stringify(t) !== first))
    throw new Error(`unsupported tuple ${JSON.stringify(ty)}`)
  return all[0]
}

const f64 = (n: number) => {
  if (!Number.isFinite(n)) throw new Error(`non-finite bound ${n}`)
  const s = String(n)
  return /[.e]/.test(s) ? (s.includes("e") && !s.includes(".") ? s.replace("e", ".0e") : s) : `${s}.0`
}

const litJson = (v: Lit) =>
  typeof v === "string" ? `rt::Lit::Str(${rustString(v)})` : typeof v === "number" ? `rt::Lit::Num(${f64(v)})` : `rt::Lit::Bool(${v})`

class Literals {
  private readonly byValue = new Map<string, string>()
  private readonly used = new Set<string>()
  private readonly values: Lit[] = []

  name(v: Lit): string {
    const key = `${typeof v}:${String(v)}`
    const existing = this.byValue.get(key)
    if (existing) return existing
    let base = typeof v === "boolean" ? (v ? "True" : "False") : typeof v === "number" ? `N${String(v).replace(/[^0-9]/g, "_")}` : pascal(v)
    if (!base) base = "Empty"
    let name = base
    for (let i = 2; this.used.has(name); i++) name = `${base}${i}`
    this.used.add(name)
    this.byValue.set(key, name)
    this.values.push(v)
    return name
  }

  emit(): string {
    let s = `/// Single-literal types: each accepts and writes exactly one JSON value.\npub mod lit {\n    use crate::wire as w;\n\n`
    // `$te` is the literal's own type error (`Expected "x"`); a literal with another message is decoded inline.
    const macro = (name: string, ty: string, arm: string, write: string) =>
      `    macro_rules! ${name} {\n        ($name:ident, $value:expr, $te:expr) => {\n            #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]\n            pub struct $name;\n\n            impl $name {\n                pub const VALUE: ${ty} = $value;\n            }\n\n            impl w::Wire for $name {\n                fn decode(v: &w::Json) -> Result<Self, w::Issue> {\n                    match v {\n                        ${arm} => Ok(Self),\n                        _ => Err(w::Issue::new($te)),\n                    }\n                }\n\n                fn encode(&self, out: &mut w::Out) {\n                    ${write}\n                }\n            }\n        };\n    }\n\n`
    let body = macro("string_literal", "&'static str", "w::Json::String(s) if s == $value", "out.string($value)")
    body += macro("number_literal", "f64", "w::Json::Number(n) if *n == $value", "out.number($value)")
    body += macro("bool_literal", "bool", "w::Json::Bool(b) if *b == $value", "out.bool($value)")
    for (const v of this.values) {
      const name = this.byValue.get(`${typeof v}:${String(v)}`)!
      const te = rustString(`Expected ${literalText(v)}`)
      if (typeof v === "string") body += `    string_literal!(${name}, ${rustString(v)}, ${te});\n`
      else if (typeof v === "number") body += `    number_literal!(${name}, ${f64(v)}, ${te});\n`
      else body += `    bool_literal!(${name}, ${v}, ${te});\n`
    }
    return `${s}${body}}\n`
  }
}

/** The TS unions' candidate data (wire/union.rs), one static per distinct site. */
class Sites {
  private readonly byKey = new Map<string, { name: string; site: Site }>()

  name(site: Site): string {
    const key = JSON.stringify(site)
    let s = this.byKey.get(key)
    if (!s) {
      s = { name: `S${this.byKey.size}`, site }
      this.byKey.set(key, s)
    }
    return s.name
  }

  emit(): string {
    const lit = (v: Lit | undefined) => (v === undefined ? "None" : `Some(${litJson(v)})`)
    let s = `/// The TS unions, as Effect's candidate index sees them: expected text, then per member its literal, sentinel\n/// fields and runtime types (see \`crate::wire::union\`).\nmod sites {\n    use crate::wire::{self as rt, Member, Site};\n\n`
    for (const { name, site } of this.byKey.values()) {
      const members = site.members.map(
        (m) =>
          `        Member { never: ${m.never === true}, literal: ${lit(m.literal)}, sentinels: &[${m.sentinels.map(([k, v]) => `(${rustString(k)}, ${litJson(v)})`).join(", ")}], types: ${m.types} },\n`,
      )
      s += `    pub static ${name}: Site = Site {\n        expected: ${rustString(site.te)},\n        members: &[\n${members.map((x) => `    ${x}`).join("")}        ],\n    };\n`
    }
    return `${s}}\n`
  }
}

class Patterns {
  private readonly byKey = new Map<string, { name: string; rust: string; source: string; flags: string }>()

  name(source: string, flags: string): string {
    const key = `${flags}/${source}`
    let p = this.byKey.get(key)
    if (!p) {
      p = { name: `P${this.byKey.size}`, rust: jsRegexToRust(source, flags), source, flags }
      this.byKey.set(key, p)
    }
    return p.name
  }

  emit(): string {
    let s = `/// Regular expressions of the schemas' pattern checks, translated from JS syntax.\nmod patterns {\n    use regex::Regex;\n    use std::sync::LazyLock;\n\n`
    for (const p of this.byKey.values())
      s += `    /// JS: \`/${p.source.replace(/`/g, "\\`")}/${p.flags}\`\n    pub static ${p.name}: LazyLock<Regex> = LazyLock::new(|| Regex::new(${rawString(p.rust)}).expect("valid pattern"));\n`
    s += `\n    #[test]\n    fn every_pattern_compiles() {\n        for p in [${[...this.byKey.values()].map((p) => `&${p.name}`).join(", ")}] {\n            LazyLock::force(p);\n        }\n    }\n`
    return `${s}}\n`
  }
}

// Definitions that reference each other directly (not through Vec / Record) need a Box to have a finite size.
function recursion(defs: Def[]): Map<string, Set<string>> {
  const direct = (ty: Ty, acc: Set<string>) => {
    switch (ty.t) {
      case "ref":
        acc.add(ty.name)
        break
      case "nullable":
      case "union1":
      case "pre":
        direct(ty.inner, acc)
        break
      case "jsonString":
        direct(ty.inner, acc)
        break
      case "custom":
        direct(ty.target ?? ty.wire, acc)
        break
    }
  }
  const edges = new Map<string, Set<string>>()
  for (const def of defs) {
    const acc = new Set<string>()
    if (def.kind === "struct") def.fields.forEach((f) => direct(f.ty, acc))
    if (def.kind === "union") def.members.forEach((m) => direct(m, acc))
    if (def.kind === "newtype") direct(def.ty, acc)
    edges.set(def.name, acc)
  }
  // Tarjan's SCC
  let index = 0
  const idx = new Map<string, number>()
  const low = new Map<string, number>()
  const stack: string[] = []
  const on = new Set<string>()
  const comp = new Map<string, number>()
  let compCount = 0
  const strong = (v: string) => {
    idx.set(v, index)
    low.set(v, index++)
    stack.push(v)
    on.add(v)
    for (const w of edges.get(v) ?? []) {
      if (!edges.has(w)) continue
      if (!idx.has(w)) {
        strong(w)
        low.set(v, Math.min(low.get(v)!, low.get(w)!))
      } else if (on.has(w)) low.set(v, Math.min(low.get(v)!, idx.get(w)!))
    }
    if (low.get(v) === idx.get(v)) {
      for (;;) {
        const w = stack.pop()!
        on.delete(w)
        comp.set(w, compCount)
        if (w === v) break
      }
      compCount++
    }
  }
  for (const def of defs) if (!idx.has(def.name)) strong(def.name)
  const out = new Map<string, Set<string>>()
  for (const def of defs) {
    const box = new Set([...edges.get(def.name)!].filter((w) => comp.get(w) === comp.get(def.name)))
    if (box.size) out.set(def.name, box)
  }
  return out
}

function emitRoots(model: Model): string {
  const names = [...new Set(model.roots.map((r) => r.name))]
  let s = HEADER("the root types, by name, for the round-trip check") + `\nuse crate::types::*;\nuse crate::wire::{self, Issue, Json};\n\n`
  s += `/// Every root type: endpoint parameters and bodies, SSE events, event definitions, the config file.\npub const ROOTS: &[&str] = &[\n${names.map((n) => `    ${JSON.stringify(n)},\n`).join("")}];\n\n`
  s += `/// Decodes \`v\` as the root type called \`name\` and writes it back; \`None\` for an unknown name.\npub fn roundtrip(name: &str, v: &Json) -> Option<Result<String, Issue>> {\n    Some(match name {\n`
  for (const n of names) s += `        ${JSON.stringify(n)} => wire::roundtrip::<${n}>(v),\n`
  s += `        _ => return None,\n    })\n}\n`
  return s
}

function emitRoutes(model: Model): string {
  const nameOf = new Map<unknown, string>(model.roots.map((r: RootTy) => [r.root, r.name]))
  const body = (b: { status: number; kind: string; contentType?: string; root?: unknown }) =>
    `Body { status: ${b.status}, kind: BodyKind::${pascal(b.kind)}, content_type: ${b.contentType ? `Some(${JSON.stringify(b.contentType)})` : "None"}, ty: ${b.root ? `Some(${JSON.stringify(nameOf.get(b.root))})` : "None"} }`
  let s = HEADER("the HttpApi route table") + "\n"
  s += `/// How a body travels.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum BodyKind {\n    /// JSON (\`application/json\`), the named type under the JSON codec.\n    Json,\n    /// No content.\n    None,\n    /// Raw bytes (\`application/octet-stream\`).\n    Binary,\n    /// Plain text.\n    Text,\n    /// Server-sent events; the named type is each event's \`data\` (JSON text).\n    Sse,\n    /// A protocol upgrade (WebSocket).\n    Upgrade,\n    /// A GET-style payload, read from the query string.\n    Query,\n    /// A raw stream.\n    Stream,\n}\n\n`
  s += `/// One response or request body: status (0 for requests), kind, content type and type name.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct Body {\n    pub status: u16,\n    pub kind: BodyKind,\n    pub content_type: Option<&'static str>,\n    pub ty: Option<&'static str>,\n}\n\n`
  s += `/// One endpoint. Type names refer to \`crate::types\` (see \`crate::roots::ROOTS\`); path, query and header types\n/// decode from the string tree the HTTP layer builds (strings, or arrays of strings for repeated query keys).\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct Route {\n    pub operation: &'static str,\n    pub group: &'static str,\n    pub method: &'static str,\n    /// \`:name\` segments are path parameters; a trailing \`*\` matches the rest of the path.\n    pub path: &'static str,\n    pub params: Option<&'static str>,\n    pub query: Option<&'static str>,\n    pub headers: Option<&'static str>,\n    pub payload: &'static [Body],\n    pub success: &'static [Body],\n    pub errors: &'static [Body],\n}\n\n`
  s += `/// Every endpoint, in declaration order.\npub const ROUTES: &[Route] = &[\n`
  for (const e of model.endpoints) {
    const opt = (r: unknown) => (r ? `Some(${JSON.stringify(nameOf.get(r))})` : "None")
    s += `    Route {\n        operation: ${JSON.stringify(e.operationId)},\n        group: ${JSON.stringify(e.group)},\n        method: ${JSON.stringify(e.method)},\n        path: ${JSON.stringify(e.path)},\n        params: ${opt(e.params)},\n        query: ${opt(e.query)},\n        headers: ${opt(e.headers)},\n`
    s += `        payload: &[${e.payload.map(body).join(", ")}],\n        success: &[${e.success.map(body).join(", ")}],\n        errors: &[${e.errors.map(body).join(", ")}],\n    },\n`
  }
  s += `];\n`
  return s
}

function emitEvents(model: Model): string {
  const nameOf = new Map<unknown, string>(model.roots.map((r: RootTy) => [r.root, r.name]))
  let s = HEADER("the event manifest") + "\n"
  s += `/// The SSE stream's event (\`GET /api/event\`): each event's \`data\` is this type's JSON text.\npub type Event = crate::types::${nameOf.get(model.sse)};\n\n`
  s += `/// The config file (\`opencode.json\`, v2 format).\npub type ConfigFile = crate::types::${nameOf.get(model.config)};\n\n`
  s += `/// An event definition from the manifest (\`EventManifest.Definitions\`).\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct EventDef {\n    pub r#type: &'static str,\n    /// The durable schema version; \`None\` for ephemeral events.\n    pub version: Option<u32>,\n    /// The event payload type in \`crate::types\`.\n    pub ty: &'static str,\n}\n\n`
  s += `/// Every event definition, in manifest order.\npub const EVENTS: &[EventDef] = &[\n`
  for (const e of model.events)
    s += `    EventDef { r#type: ${JSON.stringify(e.type)}, version: ${e.version === undefined ? "None" : `Some(${e.version})`}, ty: ${JSON.stringify(nameOf.get(e.root))} },\n`
  s += `];\n`
  return s
}
