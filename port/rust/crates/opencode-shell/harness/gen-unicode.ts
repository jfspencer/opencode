// Generates src/unicode.rs: the code points JavaScriptCore's `[\p{L}\p{Nl}]` (u flag) matches, read off the engine
// itself so the table follows the same Unicode version as the TS reference's runtime.
//
// usage: bun harness/gen-unicode.ts          write src/unicode.rs
//        bun harness/gen-unicode.ts --check  fail unless src/unicode.rs is current
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

const out = path.join(import.meta.dir, "../src/unicode.rs")
const ranges: Array<[number, number]> = []
const letter = /^[\p{L}\p{Nl}]$/u
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (!letter.test(String.fromCodePoint(cp))) continue
  const last = ranges.at(-1)
  if (last && last[1] === cp - 1) last[1] = cp
  else ranges.push([cp, cp])
}
const hex = (n: number) => `0x${n.toString(16).padStart(4, "0")}`
const rows: string[] = []
for (let i = 0; i < ranges.length; i += 6)
  rows.push("    " + ranges.slice(i, i + 6).map(([a, b]) => `(${hex(a)}, ${hex(b)})`).join(", ") + ",")
const text = `//! Generated by harness/gen-unicode.ts from the TS runtime (JavaScriptCore). Do not edit.
//! The code points \`[\\p{L}\\p{Nl}]\` matches with the \`u\` flag.

const LETTERS: &[(u32, u32)] = &[
${rows.join("\n")}
];

pub fn is_letter_or_letter_number(c: u32) -> bool {
    LETTERS
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                std::cmp::Ordering::Less
            } else if lo > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}
`
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error("src/unicode.rs is stale: run bun harness/gen-unicode.ts")
    process.exit(1)
  }
} else writeFileSync(out, text)
