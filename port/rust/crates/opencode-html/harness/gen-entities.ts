// Writes src/entities_data.rs: the HTML named character reference trie of entities@4.5.0 (the version htmlparser2
// 8.0.2 resolves in the TS reference), copied word for word so the Rust tokenizer walks the same trie.
//
// usage: bun harness/gen-entities.ts          write the file
//        bun harness/gen-entities.ts check    exit 1 if the file differs from what would be written
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const reference = join(here, "../../../../.reference")
const htmlparser2 = join(reference, "node_modules/.bun/htmlparser2@8.0.2/node_modules")
const pkg = JSON.parse(readFileSync(join(htmlparser2, "entities/package.json"), "utf8"))
if (pkg.version !== "4.5.0") throw new Error(`htmlparser2 8.0.2 resolves entities ${pkg.version}, expected 4.5.0`)
const { htmlDecodeTree } = await import(join(htmlparser2, "entities/lib/esm/decode.js"))

const words = Array.from(htmlDecodeTree as Uint16Array)
const lines: string[] = []
for (let i = 0; i < words.length; i += 16) lines.push("    " + words.slice(i, i + 16).join(", ") + ",")
const text = `// Generated by harness/gen-entities.ts from entities@4.5.0 (lib/esm/generated/decode-data-html.js). Do not edit.

/// \`htmlDecodeTree\`: the binary trie of HTML named character references.
#[rustfmt::skip]
pub(crate) static HTML_DECODE_TREE: [u16; ${words.length}] = [
${lines.join("\n")}
];
`
const target = join(here, "../src/entities_data.rs")
if (process.argv[2] === "check") {
  const current = readFileSync(target, "utf8")
  if (current !== text) {
    console.error(`${target} is out of date: run bun harness/gen-entities.ts`)
    process.exit(1)
  }
  console.log("entities_data.rs is up to date")
} else {
  writeFileSync(target, text)
  console.log(`wrote ${target} (${words.length} words)`)
}
