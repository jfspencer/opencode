// Generates grammars/wctype.c: the wide-character classification the grammar scanners get in the TS reference.
//
// Grammar WASMs import iswalpha, towupper and the rest from web-tree-sitter's tree-sitter.wasm (emscripten's
// musl), which classifies the whole of Unicode, where glibc's "C" locale knows only ASCII. This instantiates
// that tree-sitter.wasm with stub imports, evaluates each function on every code point and writes the results
// as range tables. The build force-includes grammars/wctype.h into every grammar, which renames the calls.
//
// usage: bun harness/gen-wctype.ts [check]
import { readFileSync, writeFileSync } from "fs"
import { join } from "path"

const crate = join(import.meta.dir, "..")
const reference = join(crate, "../../../.reference")
const wasmPath = join(reference, "node_modules/.bun/web-tree-sitter@0.25.10/node_modules/web-tree-sitter/tree-sitter.wasm")
const module = new WebAssembly.Module(readFileSync(wasmPath))
const imports: Record<string, Record<string, unknown>> = {}
for (const imp of WebAssembly.Module.imports(module)) {
  imports[imp.module] ??= {}
  if (imp.kind === "function") imports[imp.module][imp.name] = () => 0
  else if (imp.kind === "memory") imports[imp.module][imp.name] = new WebAssembly.Memory({ initial: 4096, maximum: 32768 })
  else if (imp.kind === "table") imports[imp.module][imp.name] = new WebAssembly.Table({ initial: 4096, element: "anyfunc" })
  else if (imp.kind === "global")
    imports[imp.module][imp.name] = new WebAssembly.Global(
      { value: "i32", mutable: imp.name !== "__memory_base" && imp.name !== "__table_base" },
      0,
    )
}
const exports = new WebAssembly.Instance(module, imports as WebAssembly.Imports).exports as Record<string, (c: number) => number>

const predicates = ["iswalnum", "iswalpha", "iswblank", "iswdigit", "iswlower", "iswspace", "iswupper", "iswxdigit"]
const maps = ["towlower", "towupper"]
let out = `// Generated by harness/gen-wctype.ts from web-tree-sitter 0.25.10's tree-sitter.wasm. Do not edit.
#include "wctype.h"

typedef struct { unsigned start, end; } range;
typedef struct { unsigned start, end; int delta; } delta_range;

static int in_ranges(const range *ranges, unsigned count, unsigned c) {
  unsigned lo = 0, hi = count;
  while (lo < hi) {
    unsigned mid = (lo + hi) / 2;
    if (c < ranges[mid].start) hi = mid;
    else if (c > ranges[mid].end) lo = mid + 1;
    else return 1;
  }
  return 0;
}

static unsigned map_ranges(const delta_range *ranges, unsigned count, unsigned c) {
  unsigned lo = 0, hi = count;
  while (lo < hi) {
    unsigned mid = (lo + hi) / 2;
    if (c < ranges[mid].start) hi = mid;
    else if (c > ranges[mid].end) lo = mid + 1;
    else return (unsigned)((int)c + ranges[mid].delta);
  }
  return c;
}
`
const MAX = 0x10ffff
for (const name of [...predicates, ...maps]) {
  const fn = exports[name]
  if (typeof fn !== "function") throw new Error(`tree-sitter.wasm exports no ${name}`)
  const isMap = maps.includes(name)
  const rows: string[] = []
  let start = -1
  let prev = 0
  const flush = (end: number) => {
    if (start < 0) return
    rows.push(isMap ? `{${start}, ${end}, ${prev}}` : `{${start}, ${end}}`)
  }
  for (let cp = 0; cp <= MAX; cp++) {
    const raw = fn(cp)
    const value = isMap ? raw - cp : raw ? 1 : 0
    if (value === 0) {
      flush(cp - 1)
      start = -1
      continue
    }
    if (start >= 0 && value === prev) continue
    flush(cp - 1)
    start = cp
    prev = value
  }
  flush(MAX)
  // Out-of-range arguments behave as in musl for the values a scanner can pass (a lookahead code point or 0).
  const table = `${name}_table`
  out += `\nstatic const ${isMap ? "delta_range" : "range"} ${table}[] = {\n  ${rows.join(",\n  ")}\n};\n`
  out += isMap
    ? `wint_t opencode_markup_${name}(wint_t c) { return c > ${MAX} ? c : map_ranges(${table}, ${rows.length}, c); }\n`
    : `int opencode_markup_${name}(wint_t c) { return c <= ${MAX} && in_ranges(${table}, ${rows.length}, c); }\n`
}

const target = join(crate, "grammars/wctype.c")
if (process.argv[2] === "check") {
  if (readFileSync(target, "utf8") !== out) {
    console.error("grammars/wctype.c is stale: run bun harness/gen-wctype.ts")
    process.exit(1)
  }
} else {
  writeFileSync(target, out)
}
