/// The errors the native core reports (the Zig error set behind a `NativeError`).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum TextError {
    InvalidOptions,
    InvalidIndex,
    InvalidCursor,
    InvalidUnicode,
    TextLimit,
    OutOfMemory,
}

impl TextError {
    /// The `NativeStatus` TS reports for this error.
    pub fn status(self) -> &'static str {
        match self {
            TextError::OutOfMemory => "OutOfMemory",
            _ => "InvalidArgument",
        }
    }
}

impl std::fmt::Display for TextError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{self:?}")
    }
}

impl std::error::Error for TextError {}
