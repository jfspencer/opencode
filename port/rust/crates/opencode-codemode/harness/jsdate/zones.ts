// Generates src/jsdate/zone_names.rs from bun: every time zone ID ICU accepts as the default zone (the system tz
// database's zones and links, plus Intl's list), its canonical ID, and the two display names toTimeString shows
// (JSC caches ICU's standard and daylight names of the current zone and picks one by the daylight flag).
//
// usage: bun harness/jsdate/zones.ts > src/jsdate/zone_names.rs
import { readFileSync } from "node:fs"

const candidates = new Set<string>(Intl.supportedValuesOf("timeZone"))
// tzdata.zi lists every zone ("Z name ...") and link ("L target name"), including backward links whose files a
// distribution may leave out.
for (const line of readFileSync("/usr/share/zoneinfo/tzdata.zi", "utf8").split("\n")) {
  const parts = line.split(/\s+/)
  if (parts[0] === "Z") candidates.add(parts[1])
  if (parts[0] === "L") candidates.add(parts[2])
}
for (const id of ["UTC", "GMT", "Etc/UTC", "Etc/GMT", "Etc/Unknown", "EST5EDT", "CST6CDT", "MST7MDT", "PST8PDT"]) candidates.add(id)

const current = () => Intl.DateTimeFormat().resolvedOptions().timeZone
// Setting process.env.TZ to an ID ICU rejects leaves the previous zone; two different sentinels tell them apart.
function resolve(id: string): string | undefined {
  process.env.TZ = "Pacific/Kiritimati"
  process.env.TZ = id
  const a = current()
  process.env.TZ = "America/Adak"
  process.env.TZ = id
  const b = current()
  return a === b ? a : undefined
}

const canonicalOf = new Map<string, string>()
for (const id of [...candidates].sort()) {
  const canonical = resolve(id)
  if (canonical !== undefined && canonical !== "Etc/Unknown") canonicalOf.set(id, canonical)
}

// The two names of a zone: toTimeString's parenthesized name, sampled weekly from 1800 to 2050. The daylight name
// is the one whose samples have the larger offset where the names change.
const DAY = 86400000
const nameRe = /\((.*)\)$/
const namesOf = new Map<string, { standard: string; daylight: string }>()
for (const canonical of new Set(canonicalOf.values())) {
  process.env.TZ = canonical
  const samples: Array<[number, string]> = []
  for (let t = Date.UTC(1800, 0, 1); t < Date.UTC(2050, 0, 1); t += 7 * DAY) {
    const d = new Date(t)
    samples.push([-d.getTimezoneOffset(), nameRe.exec(d.toTimeString())![1]])
  }
  const votes = new Map<string, number>()
  for (const [, name] of samples) if (!votes.has(name)) votes.set(name, 0)
  for (let i = 1; i < samples.length; i++) {
    const [o1, n1] = samples[i - 1]
    const [o2, n2] = samples[i]
    if (n1 === n2 || o1 === o2) continue
    const winner = o1 > o2 ? n1 : n2
    votes.set(winner, votes.get(winner)! + 1)
  }
  const names = [...votes.keys()]
  if (names.length > 2) console.error(`${canonical}: more than two names: ${names.join(" | ")}`)
  if (names.length === 1) {
    namesOf.set(canonical, { standard: names[0], daylight: names[0] })
  } else {
    const [a, b] = names
    const daylight = votes.get(a)! > votes.get(b)! ? a : b
    namesOf.set(canonical, { standard: daylight === a ? b : a, daylight })
  }
}

const rows = [...canonicalOf.entries()].sort(([a], [b]) => (a.toLowerCase() < b.toLowerCase() ? -1 : a.toLowerCase() > b.toLowerCase() ? 1 : 0))
const lines: string[] = []
lines.push("//! Generated by harness/jsdate/zones.ts from bun " + Bun.version + " (ICU " + process.versions.icu + "); do not edit.")
lines.push("//! Every zone ID ICU accepts (sorted by lowercased ID), its canonical ID, and the standard and daylight names")
lines.push("//! `toTimeString` shows for it.")
lines.push("")
lines.push("pub(super) struct ZoneEntry {")
lines.push("    pub(super) id: &'static str,")
lines.push("    pub(super) canonical: &'static str,")
lines.push("    pub(super) standard: &'static str,")
lines.push("    pub(super) daylight: &'static str,")
lines.push("}")
lines.push("")
lines.push("/// The entry for `id`, matched without regard to ASCII case as ICU does.")
lines.push("pub(super) fn lookup(id: &str) -> Option<&'static ZoneEntry> {")
lines.push("    let key = id.to_ascii_lowercase();")
lines.push("    ZONES.binary_search_by(|entry| entry.id.to_ascii_lowercase().cmp(&key)).ok().map(|index| &ZONES[index])")
lines.push("}")
lines.push("")
lines.push("const fn zone(id: &'static str, canonical: &'static str, standard: &'static str, daylight: &'static str) -> ZoneEntry {")
lines.push("    ZoneEntry { id, canonical, standard, daylight }")
lines.push("}")
lines.push("")
lines.push("#[rustfmt::skip]")
lines.push("pub(super) static ZONES: &[ZoneEntry] = &[")
for (const [id, canonical] of rows) {
  const { standard, daylight } = namesOf.get(canonical)!
  lines.push(`    zone(${JSON.stringify(id)}, ${JSON.stringify(canonical)}, ${JSON.stringify(standard)}, ${JSON.stringify(daylight)}),`)
}
lines.push("];")
console.log(lines.join("\n"))
console.error(`zones.ts: ${rows.length} IDs, ${namesOf.size} canonical zones`)
