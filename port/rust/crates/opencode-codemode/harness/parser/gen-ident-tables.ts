// Generates src/parser/ident_tables.rs: acorn's `isIdentifierStart(code, true)` and `isIdentifierChar(code, true)`
// (its BMP regex classes plus the astral tables, Unicode 16) as sorted code point ranges, evaluated by acorn itself.
//
// usage (from the crate directory): bun harness/parser/gen-ident-tables.ts > src/parser/ident_tables.rs
import { isIdentifierChar, isIdentifierStart } from "../../../../../.reference/packages/codemode/node_modules/acorn/dist/acorn.mjs"

function ranges(test: (code: number) => boolean) {
  const out: Array<[number, number]> = []
  for (let code = 0x80; code <= 0x10ffff; code++) {
    if (!test(code)) continue
    const last = out[out.length - 1]
    if (last && last[1] === code - 1) last[1] = code
    else out.push([code, code])
  }
  return out
}

function table(name: string, list: Array<[number, number]>) {
  const rows: string[] = []
  for (let i = 0; i < list.length; i += 6)
    rows.push("    " + list.slice(i, i + 6).map(([a, b]) => `(0x${a.toString(16)}, 0x${b.toString(16)})`).join(", ") + ",")
  return `pub(super) static ${name}: [(u32, u32); ${list.length}] = [\n${rows.join("\n")}\n];\n`
}

process.stdout.write(
  "// Generated by harness/parser/gen-ident-tables.ts from acorn 8.15.0; do not edit.\n" +
    "// Non-ASCII code points (>= 0x80) for which acorn's isIdentifierStart / isIdentifierChar (astral) hold.\n\n" +
    table("ID_START", ranges((c) => isIdentifierStart(c, true))) +
    "\n" +
    table("ID_CHAR", ranges((c) => isIdentifierChar(c, true))),
)
