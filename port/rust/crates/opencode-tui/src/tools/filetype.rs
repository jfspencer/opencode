/// `path.extname(input)` (POSIX): from the last `.` of the base name, unless it starts the name.
fn extname(input: &str) -> &str {
    let base = input.rsplit('/').next().unwrap_or(input);
    match base.rfind('.') {
        Some(0) | None => "",
        Some(index) => &base[index..],
    }
}

/// `filetype(input)`: `"none"` without a path, `None` (undefined) for an unknown extension.
pub fn filetype(input: Option<&str>) -> Option<&'static str> {
    let Some(input) = input.filter(|i| !i.is_empty()) else { return Some("none") };
    let ext = extname(input);
    let language = LANGUAGE_EXTENSIONS.iter().find(|(k, _)| *k == ext).map(|(_, v)| *v)?;
    if matches!(language, "typescriptreact" | "javascriptreact" | "javascript") {
        return Some("typescript");
    }
    Some(language)
}
